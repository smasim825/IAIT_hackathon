import React, { useState } from 'react';
import { HUBS } from '../data/network.js';

export default function OfflineCardModal({ route, origin, dest, landmarks, lang, onClose }) {
  const [copied, setCopied] = useState(false);
  const [downloaded, setDownloaded] = useState(false);

  if (!route) return null;

  const oName = HUBS.find((h) => h.hubId === origin)?.name || origin;
  const dName = HUBS.find((h) => h.hubId === dest)?.name || dest;

  const handleCopy = () => {
    const text = `DhakaPath Route Summary:
Trip: ${oName} ➔ ${dName}
Estimated Time: ${route.timeMinutes} mins
Fare: ৳${route.fare.min === route.fare.max ? route.fare.min : `${route.fare.min}–${route.fare.max}`}
Transfers: ${route.transfers}
Steps:
${route.legs.map((l, i) => `${i + 1}. [${l.mode.toUpperCase()}] ${l.lineId}: ${HUBS.find((h) => h.hubId === l.fromHubId)?.name} ➔ ${HUBS.find((h) => h.hubId === l.toHubId)?.name} (${l.minutes}m, ৳${l.fare.min === l.fare.max ? l.fare.min : `${l.fare.min}–${l.fare.max}`})`).join('\n')}
Generated by DhakaPath Offline Pass.`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 3000);
  };

  const generateTicketHtml = () => {
    const timestamp = new Date().toLocaleString('en-US', { timeZone: 'Asia/Dhaka' });
    const stepsHtml = route.legs.map((leg, idx) => {
      const legOrigin = HUBS.find((h) => h.hubId === leg.fromHubId)?.name || leg.fromHubId;
      const legDest = HUBS.find((h) => h.hubId === leg.toHubId)?.name || leg.toHubId;
      const noteObj = landmarks?.[leg.fromHubId];
      const note = lang === 'bn' ? (noteObj?.bn || noteObj?.en) : (noteObj?.en || noteObj?.bn);
      return `
        <div style="margin-bottom: 12px; padding: 12px; border-left: 4px solid #0284c7; background: #f8fafc; border-radius: 6px;">
          <div style="font-weight: 700; font-size: 14px; color: #0f172a;">${idx + 1}. Take ${leg.lineId} (${leg.mode.toUpperCase()}) from ${legOrigin} to ${legDest}</div>
          <div style="color: #64748b; font-size: 12px; margin: 4px 0;">${leg.km} km · ~${leg.minutes} mins · ৳${leg.fare.min === leg.fare.max ? leg.fare.min : `${leg.fare.min}–${leg.fare.max}`}</div>
          ${note ? `<div style="color: #059669; font-size: 11px; margin-top: 4px;">📍 <strong>Boarding Landmark:</strong> ${note}</div>` : ''}
        </div>
      `;
    }).join('');

    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>DhakaPath Ticket - ${oName} to ${dName}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background: #f1f5f9; padding: 24px 12px; margin: 0; color: #1e293b; }
    .ticket-container { max-width: 540px; margin: 0 auto; background: #ffffff; border-radius: 14px; border: 2px dashed #0284c7; box-shadow: 0 10px 25px rgba(0,0,0,0.08); overflow: hidden; }
    .ticket-header { background: #0f172a; color: #38bdf8; padding: 16px 20px; display: flex; justify-content: space-between; align-items: center; }
    .ticket-header h2 { margin: 0; font-size: 14px; letter-spacing: 1px; font-weight: 800; }
    .ticket-body { padding: 20px; }
    .journey-row { display: flex; justify-content: space-between; align-items: center; margin-bottom: 18px; border-bottom: 1px solid #e2e8f0; padding-bottom: 14px; }
    .station-name { font-size: 18px; font-weight: 800; color: #0f172a; }
    .station-sub { font-size: 11px; color: #64748b; }
    .stats-grid { display: grid; grid-template-columns: repeat(4, 1fr); gap: 8px; margin-bottom: 18px; }
    .stat-card { background: #f8fafc; padding: 8px; border-radius: 6px; text-align: center; border: 1px solid #e2e8f0; }
    .stat-val { font-size: 15px; font-weight: 800; color: #0284c7; }
    .stat-lbl { font-size: 10px; color: #64748b; text-transform: uppercase; }
    .footer-guarantee { background: #f0fdf4; border: 1px solid #bbf7d0; color: #166534; padding: 10px 12px; border-radius: 8px; font-size: 11px; margin-top: 14px; }
    .print-btn { display: block; width: 100%; padding: 12px; background: #0284c7; color: white; border: none; font-weight: bold; font-size: 14px; cursor: pointer; border-radius: 6px; margin-top: 18px; text-align: center; }
    @media print { .print-btn { display: none; } body { background: white; padding: 0; } .ticket-container { box-shadow: none; border: 1px solid #333; } }
  </style>
</head>
<body>
  <div class="ticket-container">
    <div class="ticket-header">
      <h2>DHAKAPATH COMMUTER TICKET</h2>
      <span style="font-size: 11px; color: #94a3b8;">${timestamp}</span>
    </div>
    <div class="ticket-body">
      <div class="journey-row">
        <div>
          <div class="station-name">${oName}</div>
          <div class="station-sub">Departure Station</div>
        </div>
        <div style="font-size: 20px; color: #0284c7;">➔</div>
        <div style="text-align: right;">
          <div class="station-name">${dName}</div>
          <div class="station-sub">Arrival Destination</div>
        </div>
      </div>
      <div class="stats-grid">
        <div class="stat-card"><div class="stat-lbl">Time</div><div class="stat-val">${route.timeMinutes}m</div></div>
        <div class="stat-card"><div class="stat-lbl">Fare</div><div class="stat-val">৳${route.fare.min === route.fare.max ? route.fare.min : `${route.fare.min}–${route.fare.max}`}</div></div>
        <div class="stat-card"><div class="stat-lbl">Transfers</div><div class="stat-val">${route.transfers}</div></div>
        <div class="stat-card"><div class="stat-lbl">Mode</div><div class="stat-val" style="font-size: 11px;">${[...new Set(route.legs.map((l) => l.mode))].join('+')}</div></div>
      </div>
      <h4 style="font-size: 13px; color: #334155; margin: 12px 0 8px 0; text-transform: uppercase;">Step-by-Step Directions</h4>
      ${stepsHtml}
      <div class="footer-guarantee">
        🛡️ <strong>Fair Fare Guarantee:</strong> Maximum allowable fare is ৳${route.fare.max}. Report unauthorized driver overcharges via DhakaPath Fare Truth.
      </div>
      <button class="print-btn" onclick="window.print()">🖨️ Print / Save as PDF</button>
    </div>
  </div>
</body>
</html>`;
  };

  const handleDownloadTicket = () => {
    try {
      const htmlContent = generateTicketHtml();
      const blob = new Blob([htmlContent], { type: 'text/html;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = `DhakaPath_Ticket_${oName}_to_${dName}.html`.replace(/\s+/g, '_');
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
      setDownloaded(true);
      setTimeout(() => setDownloaded(false), 3000);
    } catch (err) {
      console.error('Download ticket failed:', err);
    }
  };

  const handlePrintPDF = () => {
    const printWindow = window.open('', '_blank', 'width=680,height=800');
    if (printWindow) {
      printWindow.document.write(generateTicketHtml());
      printWindow.document.close();
      printWindow.focus();
      setTimeout(() => {
        printWindow.print();
      }, 400);
    } else {
      window.print();
    }
  };

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal-card" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div className="ticket-badge">DHAKAPATH COMMUTER TICKET</div>
          <button type="button" className="close-btn" onClick={onClose}>✕</button>
        </div>

        <div className="ticket-body">
          <div className="ticket-journey-row">
            <div className="ticket-point">
              <span className="point-badge">A</span>
              <div>
                <div className="ticket-hub">{oName}</div>
                <div className="ticket-sub">Departure Station</div>
              </div>
            </div>
            <div className="ticket-arrow">➔</div>
            <div className="ticket-point">
              <span className="point-badge dest">B</span>
              <div>
                <div className="ticket-hub">{dName}</div>
                <div className="ticket-sub">Arrival Destination</div>
              </div>
            </div>
          </div>

          <div className="ticket-stats-grid">
            <div className="stat-box">
              <span className="stat-label">Total Time</span>
              <span className="stat-val">{route.timeMinutes} min</span>
            </div>
            <div className="stat-box">
              <span className="stat-label">Total Fare</span>
              <span className="stat-val">৳{route.fare.min === route.fare.max ? route.fare.min : `${route.fare.min}–${route.fare.max}`}</span>
            </div>
            <div className="stat-box">
              <span className="stat-label">Transfers</span>
              <span className="stat-val">{route.transfers}</span>
            </div>
            <div className="stat-box">
              <span className="stat-label">Mode Mix</span>
              <span className="stat-val">{[...new Set(route.legs.map((l) => l.mode))].join(' + ')}</span>
            </div>
          </div>

          <div className="ticket-divider" />

          <div className="ticket-itinerary">
            <h4>Step-by-Step Directions</h4>
            <div className="itinerary-steps">
              {route.legs.map((leg, idx) => {
                const legOrigin = HUBS.find((h) => h.hubId === leg.fromHubId)?.name;
                const legDest = HUBS.find((h) => h.hubId === leg.toHubId)?.name;
                const noteObj = landmarks[leg.fromHubId];
                const note = lang === 'bn' ? (noteObj?.bn || noteObj?.en) : (noteObj?.en || noteObj?.bn);

                return (
                  <div key={idx} className="ticket-step-item">
                    <div className="step-num">{idx + 1}</div>
                    <div className="step-details">
                      <div className="step-title">
                        <b>Take {leg.lineId} ({leg.mode.toUpperCase()})</b> from {legOrigin} to {legDest}
                      </div>
                      <div className="step-sub">
                        {leg.km} km · ~{leg.minutes} mins · ৳{leg.fare.min === leg.fare.max ? leg.fare.min : `${leg.fare.min}–${leg.fare.max}`}
                      </div>
                      {note && (
                        <div className="ticket-landmark-tip">
                          📍 <b>Boarding Landmark:</b> {note}
                        </div>
                      )}
                    </div>
                  </div>
                );
              })}
            </div>
          </div>

          <div className="ticket-footer-note">
            🛡️ <b>Fair Fare Guarantee:</b> Do not pay more than ৳{route.fare.max}. If overcharged, report via DhakaPath Fare Truth.
          </div>
        </div>

        <div className="modal-actions">
          <button type="button" className="btn-secondary" onClick={handleCopy} title="Copy text to clipboard">
            {copied ? '✓ Copied!' : '📋 Copy Text'}
          </button>
          <button type="button" className="btn-download" onClick={handleDownloadTicket} title="Download offline ticket HTML">
            {downloaded ? '✓ Downloaded!' : '📥 Download Ticket'}
          </button>
          <button type="button" className="btn-primary" onClick={handlePrintPDF} title="Open print dialog to save as PDF">
            🖨️ Print / Save PDF
          </button>
        </div>
      </div>
    </div>
  );
}
